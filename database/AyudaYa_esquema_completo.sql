-- =====================================================================

CREATE OR REPLACE FUNCTION fn_validar_asignacion()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_estado_recurso text;
    v_estado_solicitud text;
BEGIN
    SELECT sr.estado, s.estado
      INTO v_estado_recurso, v_estado_solicitud
      FROM solicitud_recurso sr
      JOIN solicitud s ON s.id = sr.solicitud_id
     WHERE sr.id = NEW.solicitud_recurso_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'El recurso solicitado % no existe.', NEW.solicitud_recurso_id;
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.estado <> 'asignada' THEN
            RAISE EXCEPTION 'Una asignación nueva debe comenzar en estado asignada.';
        END IF;

        IF v_estado_recurso <> 'pendiente' THEN
            RAISE EXCEPTION 'El recurso solicitado ya no está pendiente.';
        END IF;

        IF v_estado_solicitud IN ('resuelta', 'cancelada') THEN
            RAISE EXCEPTION 'No se puede asignar un recurso de una solicitud cerrada.';
        END IF;

        NEW.asignada_at := COALESCE(NEW.asignada_at, now());
        RETURN NEW;
    END IF;

    IF NEW.solicitud_recurso_id <> OLD.solicitud_recurso_id
       OR NEW.voluntario_id IS DISTINCT FROM OLD.voluntario_id
       OR NEW.organizacion_id IS DISTINCT FROM OLD.organizacion_id
       OR NEW.asignada_por <> OLD.asignada_por
       OR NEW.asignada_at IS DISTINCT FROM OLD.asignada_at THEN
        RAISE EXCEPTION 'No se pueden cambiar el recurso, el destinatario ni el origen de la asignación.';
    END IF;

    IF OLD.estado IN ('cancelada', 'liberada') THEN
        IF NEW.estado <> OLD.estado
           OR NEW.iniciada_por IS DISTINCT FROM OLD.iniciada_por
           OR NEW.iniciada_at IS DISTINCT FROM OLD.iniciada_at
           OR NEW.completada_por IS DISTINCT FROM OLD.completada_por
           OR NEW.completada_at IS DISTINCT FROM OLD.completada_at
           OR NEW.confirmada_por IS DISTINCT FROM OLD.confirmada_por
           OR NEW.confirmada_at IS DISTINCT FROM OLD.confirmada_at
           OR NEW.cancelada_por IS DISTINCT FROM OLD.cancelada_por
           OR NEW.cancelada_at IS DISTINCT FROM OLD.cancelada_at
           OR NEW.motivo_cancelacion IS DISTINCT FROM OLD.motivo_cancelacion
           OR NEW.liberada_por IS DISTINCT FROM OLD.liberada_por
           OR NEW.liberada_at IS DISTINCT FROM OLD.liberada_at
           OR NEW.motivo_liberacion IS DISTINCT FROM OLD.motivo_liberacion THEN
            RAISE EXCEPTION 'Una asignación cerrada no se puede modificar.';
        END IF;
        RETURN NEW;
    END IF;

    IF OLD.estado = 'completada' THEN
        IF NEW.estado = 'completada' THEN
            IF OLD.confirmada_por IS NOT NULL THEN
                IF NEW.confirmada_por IS DISTINCT FROM OLD.confirmada_por
                   OR NEW.confirmada_at IS DISTINCT FROM OLD.confirmada_at
                   OR NEW.iniciada_por IS DISTINCT FROM OLD.iniciada_por
                   OR NEW.iniciada_at IS DISTINCT FROM OLD.iniciada_at
                   OR NEW.completada_por IS DISTINCT FROM OLD.completada_por
                   OR NEW.completada_at IS DISTINCT FROM OLD.completada_at THEN
                    RAISE EXCEPTION 'La asignación ya está confirmada y no se puede modificar.';
                END IF;
                RETURN NEW;
            END IF;

            IF NEW.iniciada_por IS DISTINCT FROM OLD.iniciada_por
               OR NEW.iniciada_at IS DISTINCT FROM OLD.iniciada_at
               OR NEW.completada_por IS DISTINCT FROM OLD.completada_por
               OR NEW.completada_at IS DISTINCT FROM OLD.completada_at
               OR NEW.cancelada_por IS DISTINCT FROM OLD.cancelada_por
               OR NEW.cancelada_at IS DISTINCT FROM OLD.cancelada_at
               OR NEW.motivo_cancelacion IS DISTINCT FROM OLD.motivo_cancelacion
               OR NEW.liberada_por IS DISTINCT FROM OLD.liberada_por
               OR NEW.liberada_at IS DISTINCT FROM OLD.liberada_at
               OR NEW.motivo_liberacion IS DISTINCT FROM OLD.motivo_liberacion THEN
                RAISE EXCEPTION 'No se pueden modificar los hitos de una asignación completada.';
            END IF;

            IF NEW.confirmada_por IS NOT NULL THEN
                NEW.confirmada_at := COALESCE(NEW.confirmada_at, now());
            ELSIF NEW.confirmada_at IS NOT NULL THEN
                RAISE EXCEPTION 'La confirmación requiere un usuario.';
            END IF;

            RETURN NEW;
        ELSIF NEW.estado = 'cancelada' THEN
            IF OLD.confirmada_por IS NOT NULL THEN
                RAISE EXCEPTION 'No se puede cancelar una asignación ya confirmada.';
            END IF;

            IF NEW.iniciada_por IS DISTINCT FROM OLD.iniciada_por
               OR NEW.iniciada_at IS DISTINCT FROM OLD.iniciada_at
               OR NEW.completada_por IS DISTINCT FROM OLD.completada_por
               OR NEW.completada_at IS DISTINCT FROM OLD.completada_at
               OR NEW.confirmada_por IS NOT NULL
               OR NEW.confirmada_at IS NOT NULL
               OR NEW.liberada_por IS NOT NULL
               OR NEW.liberada_at IS NOT NULL
               OR NEW.motivo_liberacion IS NOT NULL THEN
                RAISE EXCEPTION 'Cancelación inválida de una asignación completada.';
            END IF;

            NEW.cancelada_at := COALESCE(NEW.cancelada_at, now());
            RETURN NEW;
        ELSE
            RAISE EXCEPTION 'Transición no permitida desde completada hacia %.', NEW.estado;
        END IF;
    END IF;

    IF OLD.iniciada_por IS NOT NULL
       AND (NEW.iniciada_por IS DISTINCT FROM OLD.iniciada_por
            OR NEW.iniciada_at IS DISTINCT FROM OLD.iniciada_at) THEN
        RAISE EXCEPTION 'No se puede modificar el inicio registrado.';
    END IF;

    IF NEW.estado = OLD.estado THEN
        IF NEW.iniciada_por IS DISTINCT FROM OLD.iniciada_por
           OR NEW.iniciada_at IS DISTINCT FROM OLD.iniciada_at
           OR NEW.completada_por IS DISTINCT FROM OLD.completada_por
           OR NEW.completada_at IS DISTINCT FROM OLD.completada_at
           OR NEW.confirmada_por IS DISTINCT FROM OLD.confirmada_por
           OR NEW.confirmada_at IS DISTINCT FROM OLD.confirmada_at
           OR NEW.cancelada_por IS DISTINCT FROM OLD.cancelada_por
           OR NEW.cancelada_at IS DISTINCT FROM OLD.cancelada_at
           OR NEW.motivo_cancelacion IS DISTINCT FROM OLD.motivo_cancelacion
           OR NEW.liberada_por IS DISTINCT FROM OLD.liberada_por
           OR NEW.liberada_at IS DISTINCT FROM OLD.liberada_at
           OR NEW.motivo_liberacion IS DISTINCT FROM OLD.motivo_liberacion THEN
            RAISE EXCEPTION 'No se pueden modificar los hitos sin cambiar de estado.';
        END IF;
        RETURN NEW;
    END IF;

    -- La base no replica el grafo de estados de Negocio.
    -- Solo completa hitos y exige coherencia estructural.
    IF NEW.estado = 'en_atencion' THEN
        NEW.iniciada_at := COALESCE(NEW.iniciada_at, now());
        RETURN NEW;
    END IF;

    IF NEW.estado = 'completada' THEN
        IF OLD.estado <> 'en_atencion' THEN
            RAISE EXCEPTION 'Solo una asignación en atención puede completarse.';
        END IF;
        IF NEW.iniciada_por IS NULL OR NEW.iniciada_at IS NULL THEN
            RAISE EXCEPTION 'Una asignación completada debe tener inicio registrado.';
        END IF;
        IF NEW.confirmada_por IS NOT NULL OR NEW.confirmada_at IS NOT NULL THEN
            RAISE EXCEPTION 'La confirmación se registra después de completar.';
        END IF;
        NEW.completada_at := COALESCE(NEW.completada_at, now());
        RETURN NEW;
    END IF;

    IF NEW.estado = 'liberada' THEN
        IF NEW.completada_por IS NOT NULL
           OR NEW.completada_at IS NOT NULL
           OR NEW.confirmada_por IS NOT NULL
           OR NEW.confirmada_at IS NOT NULL THEN
            RAISE EXCEPTION 'No se puede liberar una asignación completada.';
        END IF;
        NEW.liberada_at := COALESCE(NEW.liberada_at, now());
        RETURN NEW;
    END IF;

    IF NEW.estado = 'cancelada' THEN
        IF NEW.completada_por IS NOT NULL
           OR NEW.completada_at IS NOT NULL
           OR NEW.confirmada_por IS NOT NULL
           OR NEW.confirmada_at IS NOT NULL
           OR NEW.liberada_por IS NOT NULL
           OR NEW.liberada_at IS NOT NULL
           OR NEW.motivo_liberacion IS NOT NULL THEN
            RAISE EXCEPTION 'Cancelación inválida de la asignación.';
        END IF;
        NEW.cancelada_at := COALESCE(NEW.cancelada_at, now());
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'Estado de asignación no permitido: %', NEW.estado;
END;
$$;

CREATE TRIGGER trg_asignacion_validar
    BEFORE INSERT OR UPDATE ON asignacion
    FOR EACH ROW EXECUTE FUNCTION fn_validar_asignacion();

