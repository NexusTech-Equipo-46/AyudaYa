CREATE OR REPLACE FUNCTION fn_validar_estado_recurso()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_estado_solicitud text;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.estado <> 'pendiente' THEN
            RAISE EXCEPTION 'Un recurso solicitado nuevo debe comenzar pendiente.';
        END IF;

        SELECT estado
          INTO v_estado_solicitud
          FROM solicitud
         WHERE id = NEW.solicitud_id;

        IF v_estado_solicitud IS NULL OR v_estado_solicitud <> 'pendiente' THEN
            RAISE EXCEPTION 'Solo se pueden agregar recursos a una solicitud pendiente.';
        END IF;

        IF NEW.resuelta_at IS NOT NULL THEN
            RAISE EXCEPTION 'Un recurso pendiente no puede tener fecha de resolución.';
        END IF;

        RETURN NEW;
    END IF;

    IF NEW.solicitud_id <> OLD.solicitud_id
       OR NEW.tipo_recurso_id <> OLD.tipo_recurso_id THEN
        RAISE EXCEPTION 'No se pueden cambiar la solicitud ni el tipo de un recurso solicitado.';
    END IF;

    IF OLD.estado <> 'pendiente'
       AND (NEW.personas <> OLD.personas
            OR NEW.detalle IS DISTINCT FROM OLD.detalle) THEN
        RAISE EXCEPTION 'No se pueden modificar personas ni detalle una vez que el recurso dejó de estar pendiente.';
    END IF;

    IF OLD.estado IN ('resuelta', 'cancelada') THEN
        IF NEW.estado <> OLD.estado
           OR NEW.personas <> OLD.personas
           OR NEW.detalle IS DISTINCT FROM OLD.detalle
           OR NEW.resuelta_at IS DISTINCT FROM OLD.resuelta_at THEN
            RAISE EXCEPTION 'Un recurso resuelto o cancelado no se puede modificar.';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.estado IN ('pendiente', 'cancelada')
       AND EXISTS (
           SELECT 1
             FROM asignacion
            WHERE solicitud_recurso_id = NEW.id
              AND estado IN ('asignada', 'en_atencion', 'completada')
       ) THEN
        RAISE EXCEPTION 'El recurso tiene una asignación activa. Cancélela o libérela antes de volver a pendiente o cancelar el recurso.';
    END IF;

    -- La base no replica el grafo de estados de Negocio.
    -- Solo mantiene coherente la fecha de resolución.
    IF NEW.estado = 'resuelta' THEN
        NEW.resuelta_at := COALESCE(NEW.resuelta_at, now());
    ELSE
        NEW.resuelta_at := NULL;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_solicitud_recurso_estado
    BEFORE INSERT OR UPDATE ON solicitud_recurso
    FOR EACH ROW EXECUTE FUNCTION fn_validar_estado_recurso();

