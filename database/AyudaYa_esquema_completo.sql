-- =====================================================================
-- AyudaYa - Esquema PostgreSQL MVP 
-- PostgreSQL 13+ / Supabase compatible
--
-- Criterios:
--   * Identity mantiene nombres estándar para mapeo directo con EF Core.
--   * Dominio en snake_case.
--   * Sin borrados físicos en usuarios, organizaciones, centros,
--     solicitudes, asignaciones, historial ni eventos.
--   * La autorización, los permisos y el grafo completo de estados
--     viven en la capa Negocio. La base solo protege invariantes
--     estructurales y evita corrupción de datos.
--   * Este archivo no habilita RLS ni revoca privilegios.
-- =====================================================================

BEGIN;
SET LOCAL TIME ZONE 'UTC';
-- gen_random_uuid() es parte del core de PostgreSQL desde la versión 13.

-- =====================================================================
-- 1. IDENTIDAD (ASP.NET Core Identity)
-- =====================================================================

CREATE TABLE "AspNetUsers" (
    "Id" uuid NOT NULL DEFAULT gen_random_uuid(),
    "UserName" text NOT NULL,
    "NormalizedUserName" text NOT NULL,
    "Email" text NOT NULL,
    "NormalizedEmail" text NOT NULL,
    "EmailConfirmed" boolean NOT NULL DEFAULT false,
    "PasswordHash" text,
    "SecurityStamp" text NOT NULL DEFAULT gen_random_uuid()::text,
    "ConcurrencyStamp" text NOT NULL DEFAULT gen_random_uuid()::text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL DEFAULT false,
    "TwoFactorEnabled" boolean NOT NULL DEFAULT false,
    "LockoutEnd" timestamptz,
    "LockoutEnabled" boolean NOT NULL DEFAULT true,
    "AccessFailedCount" integer NOT NULL DEFAULT 0,
    "NombreCompleto" text NOT NULL,
    "Activo" boolean NOT NULL DEFAULT true,
    "MotivoDesactivacion" text,
    "DesactivadoAt" timestamptz,
    "CreadoAt" timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_aspnetusers PRIMARY KEY ("Id"),
    CONSTRAINT uq_aspnetusers_normalizedusername UNIQUE ("NormalizedUserName"),
    CONSTRAINT uq_aspnetusers_normalizedemail UNIQUE ("NormalizedEmail"),
    CONSTRAINT ck_aspnetusers_email CHECK ("Email" = lower("Email")),
    CONSTRAINT ck_aspnetusers_username CHECK ("UserName" = "Email"),
    CONSTRAINT ck_aspnetusers_nombre CHECK (btrim("NombreCompleto") <> ''),
    CONSTRAINT ck_aspnetusers_desactivacion CHECK (
        ("Activo" AND "MotivoDesactivacion" IS NULL AND "DesactivadoAt" IS NULL)
        OR
        (NOT "Activo" AND "MotivoDesactivacion" IS NOT NULL AND "DesactivadoAt" IS NOT NULL)
    )
);

CREATE UNIQUE INDEX ux_aspnetusers_email_lower
    ON "AspNetUsers" (lower("Email"));

CREATE TABLE "AspNetRoles" (
    "Id" uuid NOT NULL DEFAULT gen_random_uuid(),
    "Name" text NOT NULL,
    "NormalizedName" text NOT NULL,
    "ConcurrencyStamp" text NOT NULL DEFAULT gen_random_uuid()::text,

    CONSTRAINT pk_aspnetroles PRIMARY KEY ("Id"),
    CONSTRAINT uq_aspnetroles_normalizedname UNIQUE ("NormalizedName"),
    CONSTRAINT ck_aspnetroles_name CHECK (btrim("Name") <> '')
);

CREATE TABLE "AspNetUserRoles" (
    "UserId" uuid NOT NULL,
    "RoleId" uuid NOT NULL,

    CONSTRAINT pk_aspnetuserroles PRIMARY KEY ("UserId", "RoleId"),
    CONSTRAINT fk_aspnetuserroles_user FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    CONSTRAINT fk_aspnetuserroles_role FOREIGN KEY ("RoleId")
        REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE
);

CREATE INDEX ix_aspnetuserroles_role ON "AspNetUserRoles" ("RoleId");

CREATE TABLE "AspNetUserClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" uuid NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,

    CONSTRAINT pk_aspnetuserclaims PRIMARY KEY ("Id"),
    CONSTRAINT fk_aspnetuserclaims_user FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE INDEX ix_aspnetuserclaims_user ON "AspNetUserClaims" ("UserId");

CREATE TABLE "AspNetRoleClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "RoleId" uuid NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,

    CONSTRAINT pk_aspnetroleclaims PRIMARY KEY ("Id"),
    CONSTRAINT fk_aspnetroleclaims_role FOREIGN KEY ("RoleId")
        REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE
);

CREATE INDEX ix_aspnetroleclaims_role ON "AspNetRoleClaims" ("RoleId");

CREATE TABLE "AspNetUserLogins" (
    "LoginProvider" text NOT NULL,
    "ProviderKey" text NOT NULL,
    "ProviderDisplayName" text,
    "UserId" uuid NOT NULL,

    CONSTRAINT pk_aspnetuserlogins PRIMARY KEY ("LoginProvider", "ProviderKey"),
    CONSTRAINT fk_aspnetuserlogins_user FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE INDEX ix_aspnetuserlogins_user ON "AspNetUserLogins" ("UserId");

CREATE TABLE "AspNetUserTokens" (
    "UserId" uuid NOT NULL,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text,

    CONSTRAINT pk_aspnetusertokens PRIMARY KEY ("UserId", "LoginProvider", "Name"),
    CONSTRAINT fk_aspnetusertokens_user FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- DNI separado de la tabla principal de usuarios.
-- Queda nullable para no bloquear al administrador creado por seeder;
-- la capa Negocio decide si lo exige según el tipo de cuenta.
CREATE TABLE usuario_datos_privados (
    usuario_id uuid NOT NULL,
    dni text,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_usuario_datos_privados PRIMARY KEY (usuario_id),
    CONSTRAINT fk_usuario_datos_privados_usuario FOREIGN KEY (usuario_id)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT ck_usuario_datos_privados_dni CHECK (
        dni IS NULL OR dni ~ '^[0-9]{6,9}$'
    )
);

CREATE UNIQUE INDEX ux_usuario_datos_privados_dni
    ON usuario_datos_privados (dni)
    WHERE dni IS NOT NULL;

-- =====================================================================
-- 2. GEOGRAFÍA
-- =====================================================================

CREATE TABLE ciudad (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    nombre text NOT NULL,
    provincia text NOT NULL,
    pais text NOT NULL DEFAULT 'Argentina',
    activa boolean NOT NULL DEFAULT true,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_ciudad PRIMARY KEY (id),
    CONSTRAINT ck_ciudad_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_ciudad_provincia CHECK (btrim(provincia) <> '')
);

CREATE UNIQUE INDEX ux_ciudad_nombre
    ON ciudad (lower(nombre), lower(provincia), lower(pais));

CREATE TABLE zona (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    ciudad_id uuid NOT NULL,
    nombre text NOT NULL,
    activa boolean NOT NULL DEFAULT true,
    latitud_centro double precision,
    longitud_centro double precision,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_zona PRIMARY KEY (id),
    CONSTRAINT uq_zona_id_ciudad UNIQUE (id, ciudad_id),
    CONSTRAINT fk_zona_ciudad FOREIGN KEY (ciudad_id)
        REFERENCES ciudad (id) ON DELETE RESTRICT,
    CONSTRAINT ck_zona_centro_aproximado CHECK (
        (latitud_centro IS NULL AND longitud_centro IS NULL)
        OR
        (latitud_centro BETWEEN -90 AND 90
         AND longitud_centro BETWEEN -180 AND 180)
    ),
    CONSTRAINT ck_zona_nombre CHECK (btrim(nombre) <> '')
);

CREATE UNIQUE INDEX ux_zona_nombre
    ON zona (ciudad_id, lower(nombre));

CREATE INDEX ix_zona_ciudad ON zona (ciudad_id);

-- =====================================================================
-- 3. CATÁLOGOS
-- =====================================================================

CREATE TABLE tipo_centro (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    codigo text NOT NULL,
    nombre text NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_tipo_centro PRIMARY KEY (id),
    CONSTRAINT uq_tipo_centro_codigo UNIQUE (codigo),
    CONSTRAINT ck_tipo_centro_codigo CHECK (
        codigo = lower(codigo) AND codigo ~ '^[a-z0-9_]+$'
    ),
    CONSTRAINT ck_tipo_centro_nombre CHECK (btrim(nombre) <> '')
);

CREATE TABLE tipo_recurso (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    codigo text NOT NULL,
    nombre text NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_tipo_recurso PRIMARY KEY (id),
    CONSTRAINT uq_tipo_recurso_codigo UNIQUE (codigo),
    CONSTRAINT ck_tipo_recurso_codigo CHECK (
        codigo = lower(codigo) AND codigo ~ '^[a-z0-9_]+$'
    ),
    CONSTRAINT ck_tipo_recurso_nombre CHECK (btrim(nombre) <> '')
);

-- =====================================================================
-- 4. ORGANIZACIONES
-- =====================================================================

CREATE TABLE organizacion (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    ciudad_id uuid NOT NULL,
    nombre text NOT NULL,
    tipo text NOT NULL,
    estado text NOT NULL DEFAULT 'pendiente',
    email_contacto text NOT NULL,
    telefono_contacto text NOT NULL,
    descripcion text,
    motivo_estado text,
    registrada_por uuid NOT NULL,
    aprobada_por uuid,
    aprobada_at timestamptz,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_organizacion PRIMARY KEY (id),
    CONSTRAINT uq_organizacion_id_ciudad UNIQUE (id, ciudad_id),
    CONSTRAINT fk_organizacion_ciudad FOREIGN KEY (ciudad_id)
        REFERENCES ciudad (id) ON DELETE RESTRICT,
    CONSTRAINT fk_organizacion_registrada_por FOREIGN KEY (registrada_por)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT fk_organizacion_aprobada_por FOREIGN KEY (aprobada_por)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT ck_organizacion_tipo CHECK (tipo IN ('comunitaria', 'institucional')),
    CONSTRAINT ck_organizacion_estado CHECK (
        estado IN ('pendiente', 'activa', 'rechazada', 'suspendida')
    ),
    CONSTRAINT ck_organizacion_motivo CHECK (
        (estado IN ('pendiente', 'activa') AND motivo_estado IS NULL)
        OR
        (estado IN ('rechazada', 'suspendida') AND motivo_estado IS NOT NULL)
    ),
    CONSTRAINT ck_organizacion_aprobacion CHECK (
        estado <> 'activa'
        OR (aprobada_por IS NOT NULL AND aprobada_at IS NOT NULL)
    ),
    CONSTRAINT ck_organizacion_email CHECK (email_contacto = lower(email_contacto)),
    CONSTRAINT ck_organizacion_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_organizacion_contacto CHECK (
        btrim(email_contacto) <> '' AND btrim(telefono_contacto) <> ''
    )
);

CREATE UNIQUE INDEX ux_organizacion_nombre
    ON organizacion (ciudad_id, lower(nombre));

CREATE INDEX ix_organizacion_ciudad_estado
    ON organizacion (ciudad_id, estado);

CREATE INDEX ix_organizacion_registrada_por
    ON organizacion (registrada_por);

CREATE TABLE organizacion_usuario (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    organizacion_id uuid NOT NULL,
    usuario_id uuid NOT NULL,
    rol text NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    creado_por uuid,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),
    desactivado_at timestamptz,
    motivo_baja text,

    CONSTRAINT pk_organizacion_usuario PRIMARY KEY (id),
    CONSTRAINT uq_organizacion_usuario UNIQUE (organizacion_id, usuario_id),
    CONSTRAINT fk_organizacion_usuario_org FOREIGN KEY (organizacion_id)
        REFERENCES organizacion (id) ON DELETE RESTRICT,
    CONSTRAINT fk_organizacion_usuario_usuario FOREIGN KEY (usuario_id)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT fk_organizacion_usuario_creado_por FOREIGN KEY (creado_por)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT ck_organizacion_usuario_rol CHECK (rol IN ('responsable', 'miembro')),
    CONSTRAINT ck_organizacion_usuario_activo CHECK (
        (activo AND desactivado_at IS NULL AND motivo_baja IS NULL)
        OR
        (NOT activo AND desactivado_at IS NOT NULL AND motivo_baja IS NOT NULL)
    )
);

-- Un usuario solo puede ser responsable activo de una organización.
CREATE UNIQUE INDEX ux_organizacion_usuario_responsable
    ON organizacion_usuario (usuario_id)
    WHERE rol = 'responsable' AND activo;

CREATE INDEX ix_organizacion_usuario_org
    ON organizacion_usuario (organizacion_id, rol, activo);

CREATE INDEX ix_organizacion_usuario_usuario
    ON organizacion_usuario (usuario_id);

-- =====================================================================
-- 5. CENTROS Y RECURSOS DECLARADOS
-- =====================================================================

CREATE TABLE centro (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    organizacion_id uuid NOT NULL,
    ciudad_id uuid NOT NULL,
    zona_id uuid NOT NULL,
    tipo_centro_id uuid NOT NULL,
    nombre text NOT NULL,
    direccion text NOT NULL,
    telefono_contacto text NOT NULL,
    email_contacto text,
    latitud double precision,
    longitud double precision,
    estado_verificacion text NOT NULL DEFAULT 'pendiente',
    estado_operativo text NOT NULL DEFAULT 'operativo',
    descripcion text,
    motivo_estado text,
    creado_por uuid NOT NULL,
    aprobado_por uuid,
    aprobado_at timestamptz,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_centro PRIMARY KEY (id),
    CONSTRAINT fk_centro_organizacion_ciudad FOREIGN KEY (organizacion_id, ciudad_id)
        REFERENCES organizacion (id, ciudad_id) ON DELETE RESTRICT,
    CONSTRAINT fk_centro_zona_ciudad FOREIGN KEY (zona_id, ciudad_id)
        REFERENCES zona (id, ciudad_id) ON DELETE RESTRICT,
    CONSTRAINT fk_centro_tipo FOREIGN KEY (tipo_centro_id)
        REFERENCES tipo_centro (id) ON DELETE RESTRICT,
    CONSTRAINT fk_centro_creado_por FOREIGN KEY (creado_por)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT fk_centro_aprobado_por FOREIGN KEY (aprobado_por)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT ck_centro_estado_verificacion CHECK (
        estado_verificacion IN ('pendiente', 'aprobado', 'rechazado', 'suspendido')
    ),
    CONSTRAINT ck_centro_estado_operativo CHECK (
        estado_operativo IN ('operativo', 'saturado', 'cerrado')
    ),
    CONSTRAINT ck_centro_motivo CHECK (
        (estado_verificacion IN ('pendiente', 'aprobado') AND motivo_estado IS NULL)
        OR
        (estado_verificacion IN ('rechazado', 'suspendido') AND motivo_estado IS NOT NULL)
    ),
    CONSTRAINT ck_centro_aprobacion CHECK (
        estado_verificacion <> 'aprobado'
        OR (aprobado_por IS NOT NULL AND aprobado_at IS NOT NULL)
    ),
    CONSTRAINT ck_centro_coordenadas CHECK (
        (latitud IS NULL AND longitud IS NULL)
        OR
        (latitud BETWEEN -90 AND 90 AND longitud BETWEEN -180 AND 180)
    ),
    CONSTRAINT ck_centro_email CHECK (
        email_contacto IS NULL OR email_contacto = lower(email_contacto)
    ),
    CONSTRAINT ck_centro_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_centro_direccion CHECK (btrim(direccion) <> ''),
    CONSTRAINT ck_centro_contacto CHECK (btrim(telefono_contacto) <> '')
);

CREATE UNIQUE INDEX ux_centro_nombre
    ON centro (organizacion_id, lower(nombre));

CREATE INDEX ix_centro_organizacion
    ON centro (organizacion_id, estado_verificacion);

CREATE INDEX ix_centro_ciudad_zona
    ON centro (ciudad_id, zona_id, estado_verificacion);

CREATE TABLE centro_recurso (
    centro_id uuid NOT NULL,
    tipo_recurso_id uuid NOT NULL,
    nivel text NOT NULL,
    actualizado_por uuid NOT NULL,
    actualizado_at timestamptz NOT NULL DEFAULT now(),
    creado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_centro_recurso PRIMARY KEY (centro_id, tipo_recurso_id),
    CONSTRAINT fk_centro_recurso_centro FOREIGN KEY (centro_id)
        REFERENCES centro (id) ON DELETE RESTRICT,
    CONSTRAINT fk_centro_recurso_tipo FOREIGN KEY (tipo_recurso_id)
        REFERENCES tipo_recurso (id) ON DELETE RESTRICT,
    CONSTRAINT fk_centro_recurso_actualizado_por FOREIGN KEY (actualizado_por)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT ck_centro_recurso_nivel CHECK (
        nivel IN ('alta', 'media', 'baja', 'sin_stock')
    )
);

CREATE INDEX ix_centro_recurso_tipo
    ON centro_recurso (tipo_recurso_id, nivel);

CREATE TABLE centro_horario (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    centro_id uuid NOT NULL,
    dia_semana smallint NOT NULL,
    abre time,
    cierra time,
    todo_el_dia boolean NOT NULL DEFAULT false,
    notas text,
    actualizado_por uuid NOT NULL,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_centro_horario PRIMARY KEY (id),
    CONSTRAINT fk_centro_horario_centro FOREIGN KEY (centro_id)
        REFERENCES centro (id) ON DELETE RESTRICT,
    CONSTRAINT fk_centro_horario_actualizado_por FOREIGN KEY (actualizado_por)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT ck_centro_horario_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_centro_horario_horas CHECK (
        (todo_el_dia AND abre IS NULL AND cierra IS NULL)
        OR
        (NOT todo_el_dia
         AND abre IS NOT NULL
         AND cierra IS NOT NULL
         AND abre < cierra)
    ),
    CONSTRAINT ck_centro_horario_notas CHECK (
        notas IS NULL OR btrim(notas) <> ''
    )
);

CREATE UNIQUE INDEX ux_centro_horario_turno
    ON centro_horario (centro_id, dia_semana, abre, cierra)
    WHERE abre IS NOT NULL AND cierra IS NOT NULL;

CREATE UNIQUE INDEX ux_centro_horario_todo_el_dia
    ON centro_horario (centro_id, dia_semana)
    WHERE todo_el_dia;

CREATE INDEX ix_centro_horario_centro
    ON centro_horario (centro_id, dia_semana, abre);

