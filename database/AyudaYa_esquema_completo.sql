CREATE TABLE voluntario (
    usuario_id uuid NOT NULL,
    ciudad_id uuid NOT NULL,
    zona_id uuid,
    telefono_contacto text,
    activo boolean NOT NULL DEFAULT true,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_voluntario PRIMARY KEY (usuario_id),
    CONSTRAINT fk_voluntario_usuario FOREIGN KEY (usuario_id)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT fk_voluntario_ciudad FOREIGN KEY (ciudad_id)
        REFERENCES ciudad (id) ON DELETE RESTRICT,
    CONSTRAINT fk_voluntario_zona_ciudad FOREIGN KEY (zona_id, ciudad_id)
        REFERENCES zona (id, ciudad_id) ON DELETE RESTRICT,
    CONSTRAINT ck_voluntario_telefono CHECK (
        telefono_contacto IS NULL OR btrim(telefono_contacto) <> ''
    )
);

CREATE INDEX ix_voluntario_ciudad_zona
    ON voluntario (ciudad_id, zona_id, activo);

-- =====================================================================
-- 7. SOLICITUDES
-- =====================================================================

CREATE TABLE solicitud (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    solicitante_id uuid NOT NULL,
    ciudad_id uuid NOT NULL,
    zona_id uuid NOT NULL,
    urgencia text NOT NULL DEFAULT 'normal',
    estado text NOT NULL DEFAULT 'pendiente',
    personas_afectadas integer NOT NULL,
    descripcion text,
    motivo_cancelacion text,
    cancelada_por uuid,
    cancelada_at timestamptz,
    asignada_at timestamptz,
    en_atencion_at timestamptz,
    parcial_at timestamptz,
    resuelta_at timestamptz,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_solicitud PRIMARY KEY (id),
    CONSTRAINT fk_solicitud_solicitante FOREIGN KEY (solicitante_id)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_ciudad FOREIGN KEY (ciudad_id)
        REFERENCES ciudad (id) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_zona_ciudad FOREIGN KEY (zona_id, ciudad_id)
        REFERENCES zona (id, ciudad_id) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_cancelada_por FOREIGN KEY (cancelada_por)
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT ck_solicitud_urgencia CHECK (urgencia IN ('normal', 'critica')),
    CONSTRAINT ck_solicitud_estado CHECK (
        estado IN ('pendiente', 'asignada', 'en_atencion', 'parcial', 'resuelta', 'cancelada')
    ),
    CONSTRAINT ck_solicitud_personas CHECK (personas_afectadas > 0),
    CONSTRAINT ck_solicitud_cancelacion CHECK (
        (estado = 'cancelada'
            AND motivo_cancelacion IS NOT NULL
            AND btrim(motivo_cancelacion) <> ''
            AND cancelada_por IS NOT NULL
            AND cancelada_at IS NOT NULL)
        OR
        (estado <> 'cancelada'
            AND motivo_cancelacion IS NULL
            AND cancelada_por IS NULL
            AND cancelada_at IS NULL)
    ),
    CONSTRAINT ck_solicitud_resuelta CHECK (
        (estado = 'resuelta' AND resuelta_at IS NOT NULL)
        OR (estado <> 'resuelta' AND resuelta_at IS NULL)
    ),
    CONSTRAINT ck_solicitud_descripcion CHECK (
        descripcion IS NULL OR btrim(descripcion) <> ''
    )
);

CREATE INDEX ix_solicitud_estado_ciudad
    ON solicitud (ciudad_id, estado, creado_at DESC);

CREATE INDEX ix_solicitud_solicitante
    ON solicitud (solicitante_id, creado_at DESC);

CREATE INDEX ix_solicitud_zona
    ON solicitud (zona_id, estado);

CREATE TABLE solicitud_contacto (
    solicitud_id uuid NOT NULL,
    direccion text NOT NULL,
    telefono text NOT NULL,
    latitud double precision,
    longitud double precision,
    creado_at timestamptz NOT NULL DEFAULT now(),
    actualizado_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_solicitud_contacto PRIMARY KEY (solicitud_id),
    CONSTRAINT fk_solicitud_contacto_solicitud FOREIGN KEY (solicitud_id)
        REFERENCES solicitud (id) ON DELETE RESTRICT,
    CONSTRAINT ck_solicitud_contacto_direccion CHECK (btrim(direccion) <> ''),
    CONSTRAINT ck_solicitud_contacto_telefono CHECK (btrim(telefono) <> ''),
    CONSTRAINT ck_solicitud_contacto_ubicacion CHECK (
        (latitud IS NULL AND longitud IS NULL)
        OR
        (latitud BETWEEN -90 AND 90 AND longitud BETWEEN -180 AND 180)
    )
);

CREATE TABLE solicitud_recurso (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    solicitud_id uuid NOT NULL,
    tipo_recurso_id uuid NOT NULL,
    personas integer NOT NULL,
    detalle text,
    estado text NOT NULL DEFAULT 'pendiente',
    resuelta_at timestamptz,
