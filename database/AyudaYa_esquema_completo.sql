CREATE OR REPLACE VIEW v_centros_publicos AS
SELECT
    c.id,
    c.nombre,
    tc.codigo AS tipo_centro_codigo,
    tc.nombre AS tipo_centro_nombre,
    o.id AS organizacion_id,
    o.nombre AS organizacion_nombre,
    o.tipo AS organizacion_tipo,
    ci.id AS ciudad_id,
    ci.nombre AS ciudad_nombre,
    z.id AS zona_id,
    z.nombre AS zona_nombre,
    c.direccion,
    c.telefono_contacto,
    c.email_contacto,
    c.latitud,
    c.longitud,
    c.estado_operativo,
    c.descripcion,
    c.actualizado_at AS centro_actualizado_at,
    (
        SELECT max(cr.actualizado_at)
          FROM centro_recurso cr
         WHERE cr.centro_id = c.id
    ) AS recursos_actualizado_at,
    COALESCE(
        (
            SELECT jsonb_object_agg(tr.codigo, cr.nivel)
              FROM centro_recurso cr
              JOIN tipo_recurso tr ON tr.id = cr.tipo_recurso_id
             WHERE cr.centro_id = c.id
        ),
        '{}'::jsonb
    ) AS recursos,
    (
        SELECT max(ch.actualizado_at)
          FROM centro_horario ch
         WHERE ch.centro_id = c.id
    ) AS horarios_actualizado_at,
    COALESCE(
        (
            SELECT jsonb_agg(
                       jsonb_build_object(
                           'dia_semana', ch.dia_semana,
                           'abre', ch.abre::text,
                           'cierra', ch.cierra::text,
                           'todo_el_dia', ch.todo_el_dia,
                           'notas', ch.notas
                       )
                       ORDER BY ch.dia_semana, ch.abre NULLS FIRST
                   )
              FROM centro_horario ch
             WHERE ch.centro_id = c.id
        ),
        '[]'::jsonb
    ) AS horarios
FROM centro c
JOIN organizacion o ON o.id = c.organizacion_id
JOIN ciudad ci ON ci.id = c.ciudad_id
JOIN zona z ON z.id = c.zona_id
JOIN tipo_centro tc ON tc.id = c.tipo_centro_id
WHERE c.estado_verificacion = 'aprobado'
  AND o.estado = 'activa'
  AND ci.activa
  AND z.activa;

CREATE OR REPLACE VIEW v_solicitudes_abiertas AS
SELECT
    s.id,
    s.ciudad_id,
    ci.nombre AS ciudad_nombre,
    s.zona_id,
    z.nombre AS zona_nombre,
    s.urgencia,
    s.estado,
    s.personas_afectadas,
    s.descripcion,
    s.creado_at,
    s.actualizado_at,
    COALESCE(
        (
            SELECT jsonb_agg(
                       jsonb_build_object(
                           'tipo_recurso', tr.codigo,
                           'tipo_recurso_nombre', tr.nombre,
                           'personas', sr.personas,
                           'detalle', sr.detalle,
                           'estado', sr.estado
                       )
                       ORDER BY tr.codigo
                   )
              FROM solicitud_recurso sr
              JOIN tipo_recurso tr ON tr.id = sr.tipo_recurso_id
             WHERE sr.solicitud_id = s.id
               AND sr.estado <> 'cancelada'
        ),
        '[]'::jsonb
    ) AS recursos
FROM solicitud s
JOIN ciudad ci ON ci.id = s.ciudad_id
JOIN zona z ON z.id = s.zona_id
WHERE s.estado IN ('pendiente', 'asignada', 'en_atencion', 'parcial');

CREATE OR REPLACE VIEW v_mapa_solicitudes_por_zona AS
SELECT
    s.ciudad_id,
    ci.nombre AS ciudad_nombre,
    s.zona_id,
    z.nombre AS zona_nombre,
    z.latitud_centro AS latitud_aproximada,
    z.longitud_centro AS longitud_aproximada,
    count(*) AS solicitudes_abiertas,
    COALESCE(sum(s.personas_afectadas), 0) AS personas_afectadas,
    COALESCE(
        (
            SELECT jsonb_agg(
                       jsonb_build_object(
                           'tipo_recurso', r.tipo_recurso,
                           'tipo_recurso_nombre', r.tipo_recurso_nombre,
                           'solicitudes', r.solicitudes,
                           'personas', r.personas
                       )
                       ORDER BY r.tipo_recurso
                   )
              FROM (
                  SELECT
                      tr.codigo AS tipo_recurso,
                      tr.nombre AS tipo_recurso_nombre,
                      count(DISTINCT s2.id) AS solicitudes,
                      sum(sr.personas) AS personas
                  FROM solicitud s2
                  JOIN solicitud_recurso sr ON sr.solicitud_id = s2.id
                  JOIN tipo_recurso tr ON tr.id = sr.tipo_recurso_id
                  WHERE s2.zona_id = s.zona_id
                    AND s2.estado IN ('pendiente', 'asignada', 'en_atencion', 'parcial')
                    AND sr.estado <> 'cancelada'
                  GROUP BY tr.codigo, tr.nombre
              ) r
        ),
        '[]'::jsonb
    ) AS recursos
FROM solicitud s
JOIN ciudad ci ON ci.id = s.ciudad_id
JOIN zona z ON z.id = s.zona_id
WHERE s.estado IN ('pendiente', 'asignada', 'en_atencion', 'parcial')
  AND z.latitud_centro IS NOT NULL
  AND z.longitud_centro IS NOT NULL
GROUP BY
    s.ciudad_id,
    ci.nombre,
    s.zona_id,
    z.nombre,
    z.latitud_centro,
    z.longitud_centro;

CREATE OR REPLACE VIEW v_metricas_personas_por_recurso AS
SELECT
    s.ciudad_id,
    ci.nombre AS ciudad_nombre,
    date_trunc(
        'month',
        sr.resuelta_at AT TIME ZONE 'America/Argentina/Buenos_Aires'
    )::date AS mes,
    tr.codigo AS tipo_recurso_codigo,
    tr.nombre AS tipo_recurso_nombre,
    count(*) AS recursos_resueltos,
    sum(sr.personas) AS personas_alcanzadas
FROM solicitud_recurso sr
JOIN solicitud s ON s.id = sr.solicitud_id
JOIN ciudad ci ON ci.id = s.ciudad_id
JOIN tipo_recurso tr ON tr.id = sr.tipo_recurso_id
WHERE sr.estado = 'resuelta'
GROUP BY
    s.ciudad_id,
    ci.nombre,
    date_trunc(
        'month',
        sr.resuelta_at AT TIME ZONE 'America/Argentina/Buenos_Aires'
    )::date,
    tr.codigo,
    tr.nombre;

