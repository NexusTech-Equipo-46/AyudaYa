RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_estado_solicitud text;
BEGIN
    SELECT estado
      INTO v_estado_solicitud
      FROM solicitud
     WHERE id = OLD.solicitud_id;

    IF OLD.estado <> 'pendiente' OR v_estado_solicitud <> 'pendiente' THEN
        RAISE EXCEPTION 'Solo se pueden eliminar recursos pendientes de solicitudes pendientes.';
    END IF;

    IF EXISTS (
        SELECT 1 FROM asignacion WHERE solicitud_recurso_id = OLD.id
    ) THEN
        RAISE EXCEPTION 'No se puede eliminar un recurso que ya tuvo asignaciones.';
    END IF;

    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_solicitud_recurso_no_eliminar
    BEFORE DELETE ON solicitud_recurso
    FOR EACH ROW EXECUTE FUNCTION fn_validar_eliminacion_recurso();

