-- 17. HITOS Y COHERENCIA DE LA SOLICITUD
-- =====================================================================

CREATE OR REPLACE FUNCTION fn_solicitud_hitos()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.estado <> 'pendiente' THEN
            RAISE EXCEPTION 'Una solicitud nueva debe comenzar pendiente.';
        END IF;

        NEW.motivo_cancelacion := NULL;
        NEW.cancelada_por := NULL;
        NEW.cancelada_at := NULL;
        NEW.asignada_at := NULL;
        NEW.en_atencion_at := NULL;
        NEW.parcial_at := NULL;
        NEW.resuelta_at := NULL;
        RETURN NEW;
    END IF;

    IF NEW.solicitante_id <> OLD.solicitante_id THEN
        RAISE EXCEPTION 'No se puede cambiar el solicitante.';
    END IF;

    IF OLD.estado <> 'pendiente'
       AND (NEW.ciudad_id <> OLD.ciudad_id
            OR NEW.zona_id <> OLD.zona_id
            OR NEW.urgencia <> OLD.urgencia
            OR NEW.personas_afectadas <> OLD.personas_afectadas
            OR NEW.descripcion IS DISTINCT FROM OLD.descripcion) THEN
        RAISE EXCEPTION 'La solicitud solo puede editarse mientras está pendiente.';
    END IF;

    IF OLD.estado IN ('resuelta', 'cancelada') THEN
        IF NEW.estado <> OLD.estado
           OR NEW.motivo_cancelacion IS DISTINCT FROM OLD.motivo_cancelacion
           OR NEW.cancelada_por IS DISTINCT FROM OLD.cancelada_por
           OR NEW.cancelada_at IS DISTINCT FROM OLD.cancelada_at
           OR NEW.resuelta_at IS DISTINCT FROM OLD.resuelta_at THEN
            RAISE EXCEPTION 'Una solicitud resuelta o cancelada no se puede modificar.';
        END IF;
        RETURN NEW;
    END IF;

    -- La base no replica el grafo de estados de Negocio.
    -- Mantiene hitos y la coherencia de los campos de cierre.
    IF NEW.estado = 'asignada' AND NEW.asignada_at IS NULL THEN
        NEW.asignada_at := now();
    END IF;
    IF NEW.estado = 'en_atencion' AND NEW.en_atencion_at IS NULL THEN
        NEW.en_atencion_at := now();
    END IF;
    IF NEW.estado = 'parcial' AND NEW.parcial_at IS NULL THEN
        NEW.parcial_at := now();
    END IF;

    IF NEW.estado = 'resuelta' THEN
        NEW.resuelta_at := COALESCE(NEW.resuelta_at, now());
    ELSE
        NEW.resuelta_at := NULL;
    END IF;

    IF NEW.estado = 'cancelada' THEN
        NEW.cancelada_at := COALESCE(NEW.cancelada_at, now());
        IF NEW.motivo_cancelacion IS NULL OR btrim(NEW.motivo_cancelacion) = '' THEN
            RAISE EXCEPTION 'La cancelación de la solicitud requiere motivo.';
        END IF;
        IF NEW.cancelada_por IS NULL THEN
            RAISE EXCEPTION 'La cancelación de la solicitud requiere un usuario.';
        END IF;
    ELSE
        NEW.cancelada_at := NULL;
        NEW.cancelada_por := NULL;
        NEW.motivo_cancelacion := NULL;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_solicitud_hitos
    BEFORE INSERT OR UPDATE ON solicitud
    FOR EACH ROW EXECUTE FUNCTION fn_solicitud_hitos();

