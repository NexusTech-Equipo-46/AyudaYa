CREATE OR REPLACE FUNCTION fn_verificar_solicitud_completa()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_solicitud_id uuid;
    v_estado text;
BEGIN
    IF TG_TABLE_NAME = 'solicitud' THEN
        v_solicitud_id := NEW.id;
    ELSIF TG_OP = 'DELETE' THEN
        v_solicitud_id := OLD.solicitud_id;
    ELSE
        v_solicitud_id := NEW.solicitud_id;
    END IF;

    SELECT estado
      INTO v_estado
      FROM solicitud
     WHERE id = v_solicitud_id;

    IF v_estado IS NULL OR v_estado = 'cancelada' THEN
        RETURN NULL;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM solicitud_contacto WHERE solicitud_id = v_solicitud_id
    ) THEN
        RAISE EXCEPTION
            'La solicitud % debe tener datos de contacto.', v_solicitud_id;
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM solicitud_recurso
         WHERE solicitud_id = v_solicitud_id
           AND estado <> 'cancelada'
    ) THEN
        RAISE EXCEPTION
            'La solicitud % debe tener al menos un recurso no cancelado.',
            v_solicitud_id;
    END IF;

    RETURN NULL;
END;
$$;

