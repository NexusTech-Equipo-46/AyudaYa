CREATE OR REPLACE FUNCTION fn_proteger_ultimo_responsable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_tipo_organizacion text;
    v_otros_responsables integer;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.organizacion_id <> OLD.organizacion_id
           OR NEW.usuario_id <> OLD.usuario_id THEN
            RAISE EXCEPTION 'No se puede mover una membresía de organización o usuario.';
        END IF;

        IF OLD.rol <> 'responsable'
           OR NOT OLD.activo
           OR (NEW.rol = 'responsable' AND NEW.activo) THEN
            RETURN NEW;
        END IF;
    ELSE
        IF OLD.rol <> 'responsable' OR NOT OLD.activo THEN
            RETURN OLD;
        END IF;
    END IF;

    SELECT tipo
      INTO v_tipo_organizacion
      FROM organizacion
     WHERE id = OLD.organizacion_id;

    IF v_tipo_organizacion <> 'comunitaria' THEN
        IF TG_OP = 'DELETE' THEN
            RETURN OLD;
        ELSE
            RETURN NEW;
        END IF;
    END IF;

    SELECT count(*)
      INTO v_otros_responsables
      FROM organizacion_usuario ou
      JOIN "AspNetUsers" u ON u."Id" = ou.usuario_id
     WHERE ou.organizacion_id = OLD.organizacion_id
       AND ou.id <> OLD.id
       AND ou.rol = 'responsable'
       AND ou.activo
       AND u."Activo";

    IF v_otros_responsables = 0 THEN
        RAISE EXCEPTION
            'La organización comunitaria % debe conservar al menos un responsable activo.',
            OLD.organizacion_id;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    ELSE
        RETURN NEW;
    END IF;
END;
$$;

CREATE TRIGGER trg_organizacion_usuario_ultimo_responsable
    BEFORE UPDATE OR DELETE ON organizacion_usuario
    FOR EACH ROW EXECUTE FUNCTION fn_proteger_ultimo_responsable();

CREATE OR REPLACE FUNCTION fn_proteger_ultimo_responsable_usuario()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD."Activo" AND NOT NEW."Activo" THEN
        IF EXISTS (
            SELECT 1
              FROM organizacion_usuario ou
              JOIN organizacion o ON o.id = ou.organizacion_id
             WHERE ou.usuario_id = OLD."Id"
               AND ou.rol = 'responsable'
               AND ou.activo
               AND o.tipo = 'comunitaria'
               AND NOT EXISTS (
                   SELECT 1
                     FROM organizacion_usuario ou2
                     JOIN "AspNetUsers" u2 ON u2."Id" = ou2.usuario_id
                    WHERE ou2.organizacion_id = ou.organizacion_id
                      AND ou2.id <> ou.id
                      AND ou2.rol = 'responsable'
                      AND ou2.activo
                      AND u2."Activo"
               )
        ) THEN
            RAISE EXCEPTION
                'No se puede desactivar al último responsable activo de una organización comunitaria.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_aspnetusers_ultimo_responsable
    BEFORE UPDATE ON "AspNetUsers"
    FOR EACH ROW EXECUTE FUNCTION fn_proteger_ultimo_responsable_usuario();

